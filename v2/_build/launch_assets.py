# 3) sitemap + robots
today = datetime.date.today().isoformat()
urls = [f for f in sorted(os.listdir(".")) if f.endswith(".html") and not f.startswith("_") and f != "404.html"]
urls += ["journal/" + f for f in sorted(os.listdir("journal")) if f.endswith(".html")]
def pri(u): return "1.0" if u == "index.html" else "0.8" if "/" not in u and u not in ("privacy.html", "terms.html", "connect.html") else "0.5"
for d in ("fr", "ar"):
    if os.path.isdir(d): urls += [f"{d}/{f}" for f in sorted(os.listdir(d)) if f.endswith(".html")]
xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
xml += [f"  <url><loc>{SITE}/{'' if u == 'index.html' else u}</loc><lastmod>{today}</lastmod><priority>{pri(u)}</priority></url>" for u in urls]
xml.append("</urlset>")
open("sitemap.xml", "w", encoding="utf-8", newline="\n").write("\n".join(xml) + "\n")
open("robots.txt", "w", encoding="utf-8", newline="\n").write(f"User-agent: *\nAllow: /\nDisallow: /_build/\nDisallow: /_legacy/\n\nSitemap: {SITE}/sitemap.xml\n")
print(f"sitemap: {len(urls)} urls; robots.txt written")
