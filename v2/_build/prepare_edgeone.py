"""Build an EdgeOne Makers deploy folder from the built site.
python _build/prepare_edgeone.py [--production]  -> ~/agi-edgeone-deploy (outside the repo)
- copies v2 (same exclusions as the Vercel preview), never .env* / .vercel / vercel.json
- middleware.js: all redirects from _build/redirects.csv (edgeone.json allows only 100; middleware has no limit)
- edgeone.json: noindex header for previews (omitted with --production)"""
import os, sys, csv, json, shutil, re
from urllib.parse import unquote
V2 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(os.path.expanduser("~"), "agi-edgeone-deploy")
PROD = "--production" in sys.argv
SKIP_DIRS = {"_build", "_legacy", ".git", "node_modules", "__pycache__"}
SKIP_FILES = re.compile(r"^(\.env.*|vercel\.json|\.htaccess|LAUNCH-CHECKLIST\.md|_probe_.*|.*\.bak.*)$")
if os.path.exists(OUT): shutil.rmtree(OUT)
n = size = 0
for dp, dns, fns in os.walk(V2):
    dns[:] = [d for d in dns if d not in SKIP_DIRS and not d.startswith(".")]
    rel = os.path.relpath(dp, V2)
    for f in fns:
        if SKIP_FILES.match(f) or f.startswith("."): continue
        src = os.path.join(dp, f); dst = os.path.join(OUT, rel, f) if rel != "." else os.path.join(OUT, f)
        os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(src, dst); n += 1; size += os.path.getsize(src)
# preview: noindex in every page + robots.txt that blocks crawlers
if not PROD:
    for dp, _, fns in os.walk(OUT):
        for f in fns:
            if f.endswith(".html"):
                p = os.path.join(dp, f); s = open(p, encoding="utf-8").read()
                if 'name="robots"' not in s: s = s.replace("<head>", '<head>\n<meta name="robots" content="noindex, nofollow">', 1)
                open(p, "w", encoding="utf-8", newline="").write(s)
    open(os.path.join(OUT, "robots.txt"), "w").write("User-agent: *\nDisallow: /\n")
# EdgeOne limit: 25 MB per file (LIMIT_25MB) - drop larger files from the deploy copy and replace their links with a note
LIMIT = 25 * 1048576
too_big = [os.path.join(dp, f) for dp, _, fns in os.walk(OUT) for f in fns if os.path.getsize(os.path.join(dp, f)) > LIMIT]
for fp in too_big:
    rel = os.path.relpath(fp, OUT).replace(os.sep, "/"); name = os.path.basename(fp); os.remove(fp)
    for dp, _, fns in os.walk(OUT):
        for f in fns:
            if f.endswith(".html"):
                hp = os.path.join(dp, f); s = open(hp, encoding="utf-8").read()
                if name in s:
                    s = re.sub(r'<a[^>]*href="[^"]*' + re.escape(name) + r'"[^>]*>.*?</a>', '<span class="muted">This video is being moved to the new site.</span>', s, flags=re.S)
                    open(hp, "w", encoding="utf-8", newline="").write(s)
    print(f"dropped (over 25 MB): {rel}")
# redirects -> middleware.js
rows = list(csv.DictReader(open(os.path.join(V2, "_build", "redirects.csv"), encoding="utf-8-sig")))
table = {}
for r in rows:
    old = unquote(r["old_address"]).rstrip("/") or "/"
    new = r["new_page"]
    if old != "/" and old != new: table[old.lower()] = new
mw = """// Generated by v2/_build/prepare_edgeone.py – old WordPress addresses -> new pages (301).
const REDIRECTS = %s;
export function middleware(context) {
  const url = new URL(context.request.url);
  let path;
  try { path = decodeURIComponent(url.pathname); } catch (e) { path = url.pathname; }
  const key = (path.replace(/\\/+$/, '') || '/').toLowerCase();
  const target = REDIRECTS[key];
  if (target && target !== url.pathname) return context.redirect(new URL(target, url.origin).toString(), 301);
  return context.next();
}
""" % json.dumps(table, ensure_ascii=False, indent=0)
open(os.path.join(OUT, "middleware.js"), "w", encoding="utf-8").write(mw)
cfg = {"headers": [{"source": "/*", "headers": [{"key": "X-Robots-Tag", "value": "noindex, nofollow"}]}]} if not PROD else {}
cfg.setdefault("headers", []).append({"source": "/assets/*", "headers": [{"key": "Cache-Control", "value": "public, max-age=31536000, immutable"}]})
json.dump(cfg, open(os.path.join(OUT, "edgeone.json"), "w", encoding="utf-8"), indent=2)
big = [(os.path.relpath(os.path.join(dp, f), OUT), os.path.getsize(os.path.join(dp, f)) // 1048576) for dp, _, fns in os.walk(OUT) for f in fns if os.path.getsize(os.path.join(dp, f)) > 20 * 1048576]
print(f"edgeone deploy folder: {OUT}\nfiles: {n}  size: {size // 1048576} MB  redirects in middleware: {len(table)}  mode: {'production' if PROD else 'preview (noindex)'}")
if big: print("files over 20 MB:", big)
leaks = [f for dp, _, fns in os.walk(OUT) for f in fns if f.startswith(".env") or f == "vercel.json"]
print("secrets/vercel files in folder:", leaks or "none")
